// 一段甩动 = [t0, t1, 起, 止]：越转越快，到头撞上限位销一下停住
function swings(tr, e, v) {
  for (const s of tr) {
    if (e < s[0]) break;
    v = e < s[1] ? s[2] + (s[3] - s[2]) * Math.pow((e - s[0]) / (s[1] - s[0]), 1.7) : s[3];
  }
  return v;
}
// 甩的那一下手腕跟着一抖：正在甩的那一段里按 sin 起伏
