// 高精度模型：AK 以外的枪、手雷、C4。
// 都是照真枪的大致尺寸自己搭的（见 hdkit.js），没有用任何游戏的模型或贴图。
// 约定：-Z 是枪口，+Y 朝上，+X 是右边；要单独动的零件放在有名字的组里：
//   mag 弹匣、bolt 枪机 / 套筒 / 拉机柄、pump 霰弹枪护木、pin 手雷拉环
// userData：muzzle 枪口位置，boltTravel 拉机柄能拉多远，boltKick 开枪时自己弹多远，manual 栓动（不会自己弹），boltLift 拉机柄抬起的角度
import * as THREE from 'three';
import { arcPts, rrect } from './hdkit.js';

const U = 0.00116; // 真枪的 1 毫米 = 模型里的这么多米
const T = (x, y, z) => new THREE.Matrix4().makeTranslation(x, y, z);
const V = (x, y, z) => new THREE.Vector3(x, y, z);
const circle = (z, y, r, n = 10) => arcPts(z, y, r, 0, Math.PI * 2, n).slice(0, -1);

// ============================== 手枪 ==============================
// o：L 套筒长，H 套筒高，W 套筒宽，slide / frame 材质，cham 套筒顶上削掉的斜角，sup 带消音器，hammer 有击锤，f 握把放大多少
function pistol(k, o) {
  const { L, H, W } = o, top = 0.0235 + H, zf = 0.03 - L, YB = top - 0.015, f = o.f ?? 1;
  // 套筒（开枪、拉套筒时往后滑）
  k.group('bolt', () => {
    const c = o.cham ?? 0.004;
    k.sweep(o.slide, [[-W / 2, 0.0235], [W / 2, 0.0235], [W / 2, top - c], [W / 2 - c, top], [-W / 2 + c, top], [-W / 2, top - c]], zf, 0.03, { bevel: 0.0012 });
    k.fine(() => {
      k.box('bore', 0.0125, 0.0035, 0.03, W / 2 - 0.0085, top - 0.001, zf + L * 0.42, { r: 0.001 });  // 抛壳窗
      for (let i = 0; i < 6; i++) for (const s of [-1, 1]) k.box(o.slide, 0.0012, H * 0.62, 0.0022, s * (W / 2), 0.0235 + H * 0.45, 0.02 - i * 0.0052, { r: 0.0004 }); // 防滑纹
      k.box('black', 0.004, 0.004, 0.006, 0, top + 0.002, zf + 0.012, { r: 0.0008 });               // 准星
      k.box('black', 0.016, 0.005, 0.007, 0, top + 0.0025, 0.02, { r: 0.0008 });                    // 照门
    });
  });
  // 枪管（不跟着套筒动：套筒拉开时会露出来）
  k.tube('steel', 0.0068, zf - 0.002, zf + 0.07, { y: YB });
  k.ball('bore', 0.0046, 0.0046, 0.002, T(0, YB, zf - 0.0018));
  let mz = zf - 0.008;
  if (o.sup) {
    // 消音器
    k.tube('black', 0.0158, zf - 0.19, zf - 0.004, { y: YB });
    k.tube('black', 0.0165, zf - 0.19, zf - 0.178, { y: YB });
    k.fine(() => { for (let i = 0; i < 3; i++) k.tube('blued', 0.0162, zf - 0.03 - i * 0.008, zf - 0.026 - i * 0.008, { y: YB }); });
    k.ball('bore', 0.0052, 0.0052, 0.002, T(0, YB, zf - 0.1905));
    mz = zf - 0.196;
  }
  // 套筒座 + 握把（侧面一整块）、扳机护圈、扳机
  const F = (pts) => pts.map(([z, y]) => [z * f, y < 0 ? y * f : y]);
  k.prof(o.frame, F([[zf + 0.01, 0.0235], [0.03, 0.0235], [0.042, 0.014], [0.038, -0.008], [0.07, -0.098], [0.016, -0.105], [-0.022, -0.004], [-0.03, 0.002], [zf + 0.01, 0.006]]), W + 0.002, { bevel: 0.0045 });
  k.prof(o.frame, F([[-0.1, 0.006], [-0.1, -0.026], [-0.09, -0.036], [-0.03, -0.036], [-0.018, -0.022], [-0.022, -0.016], [-0.034, -0.03], [-0.086, -0.03], [-0.093, -0.023], [-0.093, 0.006]]), 0.014, { bevel: 0.002 });
  k.prof('black', F([[-0.05, 0.004], [-0.043, 0.004], [-0.045, -0.014], [-0.052, -0.024], [-0.055, -0.022], [-0.05, -0.012]]), 0.007, { bevel: 0.0012 });
  k.fine(() => {
    for (const s of [-1, 1]) k.prof('black', F([[0.004, -0.02], [0.036, -0.014], [0.058, -0.088], [0.024, -0.094]]), 0.0012, { x: s * (W / 2 + 0.0012), bevel: 0.0005 }); // 握把贴片
    k.box('black', 0.006, 0.005, 0.014, -(W / 2 + 0.002), 0.017, -0.012, { r: 0.0012 }); // 空仓挂机
  });
  if (o.hammer) k.prof('blued', [[0.03, 0.03], [0.041, 0.036], [0.041, 0.045], [0.035, 0.047], [0.03, 0.04]], 0.006, { bevel: 0.001 });
  // 弹匣：平时藏在握把里，只露出底板；换弹时顺着握把往下抽
  k.group('mag', () => {
    k.prof('steel', F([[-0.012, -0.004], [0.03, -0.004], [0.062, -0.097], [0.022, -0.103]]), 0.019, { bevel: 0.002 });
    k.prof('black', F([[0.012, -0.103], [0.072, -0.096], [0.074, -0.106], [0.012, -0.114]]), W, { bevel: 0.003 });
  });
  const g = k.build();
  g.userData.muzzle = V(0, YB, mz);
  g.userData.boltTravel = Math.min(0.045, L * 0.2);
  g.userData.boltKick = 0.03;
  g.userData.dims = { top, zf, YB, f };
  return g;
}

// ============================== M4A4 / M4A1-S ==============================
// 尺寸是真枪上的毫米数：离枪口（消焰器前端）多远、比枪管轴线高多少
function m4(k, sil) {
  const YB = 0.04, Z = (mm) => -0.70 + mm * U, Y = (mm) => YB + mm * U;
  const P = (...pts) => pts.map(([a, b]) => [Z(a), Y(b)]);
  const X = (pts) => pts.map(([a, b]) => [a * U, Y(b)]);
  // ---- 枪口、枪管 ----
  if (sil) {
    k.tube('black', 19 * U, Z(-150), Z(62), { y: YB });
    k.tube('black', 20 * U, Z(-150), Z(-138), { y: YB });
    k.fine(() => { for (let i = 0; i < 4; i++) k.tube('blued', 19.6 * U, Z(30 - i * 9), Z(34 - i * 9), { y: YB }); });
    k.ball('bore', 6 * U, 6 * U, 2 * U, T(0, YB, Z(-150) - 0.0004));
  } else {
    k.tube('blued', 11 * U, Z(0), Z(44), { y: YB });
    k.tube('blued', 9.6 * U, Z(44), Z(52), { y: YB });
    k.ball('bore', 4.6 * U, 4.6 * U, 2 * U, T(0, YB, Z(0) - 0.0004));
  }
  k.tube('blued', 9 * U, Z(40), Z(220), { y: YB });
  // ---- 准星座（三角架）----
  k.prof('blued', P([166, 6], [206, 6], [198, 30], [203, 54], [176, 54], [181, 30]), 12 * U, { bevel: 0.001 });
  k.tube('blued', 12 * U, Z(170), Z(204), { y: YB });
  k.rod('steel', 1.6 * U, [0, Y(52), Z(189)], [0, Y(66), Z(189)]);
  for (const s of [-1, 1]) k.prof('blued', P([180, 52], [198, 52], [200, 68], [178, 68]), 2.2 * U, { x: s * 6.5 * U, bevel: 0.0004 });
  k.tube('steel', 3.2 * U, Z(200), Z(390), { y: Y(19) }); // 导气管
  // ---- 护木（上下两片，带散热孔的圆筒）----
  k.sweep('black', X([[-20, -27], [20, -27], [28, -14], [28, 14], [20, 28], [-20, 28], [-28, 14], [-28, -14]]), Z(218), Z(386), { bevel: 0.003 });
  k.fine(() => {
    for (let i = 0; i < 7; i++) k.sweep('black', X([[-21, -28], [21, -28], [29, -14.5], [29, 14.5], [21, 29], [-21, 29], [-29, 14.5], [-29, -14.5]]), Z(232 + i * 21), Z(238 + i * 21), { bevel: 0.0008 });
  });
  k.tube('blued', 29 * U, Z(386), Z(400), { y: YB, r1: 24 * U }); // 护木卡箍
  // ---- 上机匣（平顶，带导轨）、下机匣、弹匣井 ----
  k.prof('blued', P([400, -22], [612, -22], [612, 30], [596, 35], [402, 35]), 36 * U, { bevel: 0.002 });
  k.fine(() => {
    for (let i = 0; i < 13; i++) k.box('blued', 20 * U, 4 * U, 6 * U, 0, Y(37.5), Z(412 + i * 13.5), { r: 0.0005 }); // 导轨的齿
    k.box('bore', 3 * U, 14 * U, 58 * U, 18.4 * U, Y(11), Z(472), { r: 0.0008 });            // 抛壳窗
    k.prof('blued', P([504, 2], [520, 2], [512, 22]), 8 * U, { x: 20 * U, bevel: 0.0008 });  // 抛壳挡板
    k.rod('blued', 4.5 * U, [19 * U, Y(18), Z(548)], [27 * U, Y(18), Z(556)]);                // 辅助推机柄
    k.box('blued', 4 * U, 9 * U, 26 * U, -19.5 * U, Y(-8), Z(520), { r: 0.0008 });           // 空仓挂机 / 弹匣卡笋
    k.pin('steel', 3 * U, -18.6 * U, 18.6 * U, Y(-16), Z(604));
    k.pin('steel', 3 * U, -18.6 * U, 18.6 * U, Y(-16), Z(428));
  });
  k.prof('blued', P([432, -22], [432, -76], [494, -72], [497, -54], [560, -54], [566, -42], [612, -42], [622, -22]), 30 * U, { bevel: 0.002 });
  k.prof('blued', P([495, -77], [563, -77], [563, -80.5], [495, -80.5]), 12 * U, { bevel: 0.0006 }); // 扳机护圈
  k.prof('steel', P([524, -54], [531, -54], [530, -66], [525, -76], [521, -74], [524, -64]), 5 * U, { bevel: 0.0008 }); // 扳机
  // ---- 照门 ----
  k.prof('blued', P([578, 35], [606, 35], [606, 44], [598, 62], [586, 62], [578, 44]), 22 * U, { bevel: 0.0012 });
  k.fine(() => k.ball('bore', 2.6 * U, 2.6 * U, 15 * U, T(0, Y(54), Z(592)))); // 觇孔
  // ---- 握把、枪托 ----
  k.prof('black', P([560, -42], [602, -42], [608, -56], [634, -142], [602, -152], [580, -98], [566, -58]), 30 * U, { bevel: 0.0055 });
  k.tube('blued', 15 * U, Z(620), Z(772), { y: Y(-2) }); // 缓冲管
  k.prof('black', P([664, 16], [800, 16], [809, 6], [809, -96], [792, -100], [742, -32], [664, -24]), 40 * U, { bevel: 0.006 });
  k.fine(() => k.prof('blued', P([803, 12], [812, 12], [812, -98], [803, -98]), 34 * U, { bevel: 0.002 })); // 托底板
  // ---- 拉机柄（机匣后上方的 T 形柄）----
  k.group('bolt', () => {
    k.box('blued', 34 * U, 7 * U, 16 * U, 0, Y(31), Z(617), { r: 0.0012 });
    k.box('blued', 12 * U, 6 * U, 40 * U, 0, Y(31), Z(596), { r: 0.001 });
  });
  // ---- 弹匣 ----
  k.group('mag', () => {
    // 弹匣下半截往前弯（M4A1-S 是 20 发的短直弹匣）
    if (sil) k.prof('steel', P([438, -60], [490, -60], [487, -152], [434, -150]), 24 * U, { bevel: 0.002 });
    else k.prof('steel', P([438, -60], [490, -60], [487, -138], [474, -208], [421, -197], [434, -138]), 24 * U, { bevel: 0.002 });
    k.fine(() => { for (const s of [-1, 1]) k.prof('steel', P([452, -70], [476, -70], [473, -136], [449, -136]), 1.2 * U, { x: s * 12.4 * U, bevel: 0.0004 }); });
  });
  const g = k.build();
  g.userData.muzzle = V(0, YB, (sil ? Z(-150) : Z(0)) - 0.01);
  g.userData.boltTravel = 0.06;
  g.userData.boltKick = 0;
  return g;
}

// ============================== 栓动狙击枪（AWP / SSG 08） ==============================
// o：big = AWP（粗枪管、制退器、绿色枪托），否则是鸟狙（细枪管、深色枪托）
function sniper(k, o) {
  const big = !!o.big, YB = 0.045, body = big ? 'olive' : 'slate';
  const rr = big ? 0.021 : 0.018, zb = big ? -0.8 : -0.76, ys = big ? 0.118 : 0.108; // 机匣半径、枪口、瞄准镜高度
  // ---- 枪管、枪口 ----
  k.tube('blued', big ? 0.0125 : 0.0088, zb, -0.3, { y: YB, r1: big ? 0.0145 : 0.011 });
  if (big) {
    k.tube('blued', 0.019, -0.8, -0.735, { y: YB });
    k.fine(() => { for (const z of [-0.785, -0.765, -0.748]) for (const s of [-1, 1]) k.box('bore', 0.004, 0.014, 0.008, s * 0.0175, YB, z, { r: 0.001 }); });
  } else k.tube('blued', 0.0105, -0.76, -0.735, { y: YB });
  k.ball('bore', 0.0052, 0.0052, 0.002, T(0, YB, zb - 0.0004));
  // ---- 机匣 ----
  k.tube('blued', rr, -0.3, 0.14, { y: YB });
  k.fine(() => {
    k.box('bore', 0.004, 0.014, 0.075, rr - 0.0015, YB + 0.004, -0.06, { r: 0.001 }); // 抛壳窗
    k.tube('blued', rr + 0.002, -0.305, -0.285, { y: YB });
  });
  // ---- 枪托（带拇指孔的一整块）、扳机护圈、扳机 ----
  k.prof(body, [[-0.37, 0.036], [0.15, 0.036], [0.175, 0.072], [0.42, 0.072], [0.44, 0.06], [0.44, -0.062], [0.41, -0.068], [0.23, -0.036], [0.165, -0.046],
    [0.14, -0.112], [0.098, -0.116], [0.078, -0.03], [0.055, -0.012], [-0.14, -0.012], [-0.2, 0.002], [-0.37, 0.006]], big ? 0.05 : 0.042,
  { bevel: 0.008, holes: [[[0.175, -0.024], [0.3, -0.012], [0.31, 0.03], [0.19, 0.032]]] });
  k.prof('blued', [[-0.02, -0.012], [-0.02, -0.04], [0.05, -0.04], [0.072, -0.028], [0.067, -0.023], [0.046, -0.034], [-0.014, -0.034], [-0.014, -0.012]], 0.012, { bevel: 0.0015 });
  k.prof('steel', [[0.018, -0.012], [0.025, -0.012], [0.024, -0.022], [0.018, -0.031], [0.014, -0.029], [0.018, -0.02]], 0.006, { bevel: 0.001 });
  k.fine(() => k.prof('black', [[0.4, 0.074], [0.445, 0.062], [0.445, -0.064], [0.43, -0.068], [0.43, 0.072]], big ? 0.046 : 0.038, { bevel: 0.004 })); // 托底板
  // ---- 弹匣 ----
  k.group('mag', () => k.prof('black', [[-0.125, -0.005], [-0.03, -0.005], [-0.034, -0.072], [-0.121, -0.072]], big ? 0.036 : 0.03, { bevel: 0.003 }));
  // ---- 瞄准镜 ----
  const rs = big ? 1 : 0.86;
  k.lathe('black', [[-0.3, 0.031 * rs], [-0.235, 0.031 * rs], [-0.2, 0.0165 * rs], [0.02, 0.0165 * rs], [0.05, 0.0225 * rs], [0.112, 0.0235 * rs], [0.116, 0.02 * rs]], { y: ys });
  k.ball('lens', 0.028 * rs, 0.028 * rs, 0.004, T(0, ys, -0.297));
  k.ball('lens', 0.019 * rs, 0.019 * rs, 0.003, T(0, ys, 0.114));
  k.rod('black', 0.0105, [0, ys + 0.012, -0.09], [0, ys + 0.036, -0.09]);       // 上面的调节旋钮
  k.rod('black', 0.0105, [0.012, ys, -0.09], [0.036, ys, -0.09]);               // 侧面的调节旋钮
  for (const z of [-0.165, 0.0]) {                                                  // 两个镜架
    k.box('blued', 0.016, ys - YB - rr + 0.012, 0.022, 0, (ys + YB + rr) / 2 - 0.004, z, { r: 0.002 });
    k.tube('blued', 0.0195 * rs, z - 0.011, z + 0.011, { y: ys });
  }
  // ---- 枪栓（转轴在枪栓轴线上：抬拉机柄就是绕它转）----
  k.group('bolt', () => {
    k.tube('bright', 0.0108, 0.0, 0.168, { y: YB });
    k.tube('blued', 0.0125, 0.14, 0.172, { y: YB });
    k.rod('blued', 0.0052, [0.01, YB - 0.004, 0.118], [0.046, YB - 0.024, 0.122]);
    k.ball('blued', 0.0115, 0.0115, 0.0115, T(0.05, YB - 0.027, 0.122));
  }, { pivot: [0, YB, 0.1] });
  const g = k.build();
  g.userData.muzzle = V(0, YB, zb - 0.01);
  g.userData.boltTravel = 0.085;
  g.userData.boltLift = 1.05;
  g.userData.manual = true;
  return g;
}

