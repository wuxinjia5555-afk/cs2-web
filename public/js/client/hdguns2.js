// 高精度模型（第二批）：CS2 里其余的枪 —— 冲锋枪（MP7、MP5-SD、P90、野牛）、霰弹枪（XM1014、截短霰弹枪、MAG-7）、
// 机枪（M249、内格夫）、步枪（SG 553、AUG）、连狙（G3SG1、SCAR-20）、TEC-9、R8 左轮。
// 和 hdguns.js 一样：照真枪的大致尺寸自己搭的，没有用任何游戏的模型或贴图。
// 约定：-Z 是枪口，+Y 朝上，+X 是右边；尺寸多数按真枪上的毫米数写（离枪口多远、比枪管轴线高多少）。
// 会动的零件放在有名字的组里：mag 弹匣、bolt 拉机柄、pump 护木，另外还有
//   cover 机枪的受弹机盖（绕前面的轴往上掀）、cyl 左轮的弹巢（往左甩出来）、hammer 击锤
import * as THREE from 'three';
import { arcPts, rrect } from './hdkit.js';

const U = 0.00116; // 真枪的 1 毫米 = 模型里的这么多米
const T = (x, y, z) => new THREE.Matrix4().makeTranslation(x, y, z);
const V = (x, y, z) => new THREE.Vector3(x, y, z);
// 一把枪自己的尺子：z0 = 枪口在哪，yb = 枪管轴线多高。Z(毫米) 离枪口多远，Y(毫米) 比枪管轴线高多少；P 侧面轮廓的点，X 横截面的点
function ruler(z0, yb) {
  const Z = (mm) => z0 + mm * U, Y = (mm) => yb + mm * U;
  return { z0, yb, Z, Y, P: (...pts) => pts.map(([a, b]) => [Z(a), Y(b)]), X: (pts) => pts.map(([a, b]) => [a * U, Y(b)]) };
}
// 顶上的一段导轨：从 a 到 b（毫米），顶面比枪管轴线高 h，w 宽
function rail(k, R, mat, a, b, h, w = 21) {
  k.box(mat, w * U, 5 * U, (b - a) * U, 0, R.Y(h - 2.5), R.Z((a + b) / 2), { r: 0.0008 });
  k.fine(() => { for (let m = a + 6; m < b - 3; m += 10) k.box(mat, (w + 1.6) * U, 3.4 * U, 5.2 * U, 0, R.Y(h + 1), R.Z(m), { r: 0.0004 }); });
}
// 扳机护圈（a~b 前后，top 顶、bot 底）和扳机（在 t 这里）
function guard(k, R, mat, a, b, top, bot, t, w = 13) {
  k.prof(mat, R.P([a, bot + 3.5], [b, bot + 3.5], [b, bot], [a, bot]), w * U, { bevel: 0.0005 });
  k.prof(mat, R.P([a - 4, top], [a, top], [a + 4, bot], [a, bot]), w * U, { bevel: 0.0005 });
  k.prof(mat, R.P([b - 4, bot], [b, bot], [b + 9, top - 4], [b + 5, top - 4]), w * U, { bevel: 0.0005 });
  k.prof('steel', R.P([t, top], [t + 7, top], [t + 6, top - 11], [t + 1.5, top - 24], [t - 3, top - 22], [t, top - 11]), 5 * U, { bevel: 0.0008 });
}
// 枪口里面
const bore = (k, R, r, mm = 0) => k.ball('bore', r * U, r * U, 2 * U, T(0, R.yb, R.Z(mm) - 0.0004));
// 瞄准镜：镜筒从 a 到 b（毫米），中心比枪管轴线高 h；r 镜筒半径，obj / eye 物镜、目镜那头的半径；两个镜架落到 base 这个高度
function scope(k, R, a, b, h, r, obj, eye, base, mounts) {
  const L = b - a;
  k.lathe('black', [[R.Z(a), obj * U], [R.Z(a + L * 0.2), obj * U], [R.Z(a + L * 0.3), r * U], [R.Z(b - L * 0.3), r * U], [R.Z(b - L * 0.2), eye * U], [R.Z(b - 3), eye * U], [R.Z(b), (eye - 2) * U]], { y: R.Y(h) });
  k.ball('lens', (obj - 2) * U, (obj - 2) * U, 3 * U, T(0, R.Y(h), R.Z(a + 3)));
  k.ball('lens', (eye - 3) * U, (eye - 3) * U, 2.5 * U, T(0, R.Y(h), R.Z(b - 2)));
  const mid = (a + b) / 2;
  k.rod('black', 9 * U, [0, R.Y(h + r - 2), R.Z(mid)], [0, R.Y(h + r + 18), R.Z(mid)]);          // 上面的调节旋钮
  k.rod('black', 9 * U, [(r - 2) * U, R.Y(h), R.Z(mid)], [(r + 18) * U, R.Y(h), R.Z(mid)]);      // 侧面的调节旋钮
  for (const m of mounts) {
    k.box('blued', 15 * U, (h - r - base + 8) * U, 18 * U, 0, R.Y((h - r + base) / 2 + 2), R.Z(m), { r: 0.0015 });
    k.tube('blued', (r + 3) * U, R.Z(m - 8), R.Z(m + 8), { y: R.Y(h) });
  }
}
// 圆柱形消焰器 / 制退器上的一圈开槽
function slots(k, R, n, rad, a, len, w = 3.4) {
  k.fine(() => {
    for (let i = 0; i < n; i++) {
      const ang = (i / n) * Math.PI * 2 + 0.5;
      k.box('bore', w * U, 2.2 * U, len * U, Math.sin(ang) * rad * U, R.yb + Math.cos(ang) * rad * U, R.Z(a), { r: 0.0005, rz: -ang });
    }
  });
}
const done = (k, R, o = {}) => {
  const g = k.build();
  g.userData.muzzle = V(0, R.yb, R.Z(o.mz ?? 0) - 0.012);
  Object.assign(g.userData, o.u || {});
  return g;
};

